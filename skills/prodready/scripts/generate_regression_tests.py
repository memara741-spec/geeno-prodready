#!/usr/bin/env python3
"""Generate regression tests that prove a fix worked and that it did not break the app.

Reads the findings from a scan (``.prodready/findings.json``) and writes tests
into ``<app_root>/.prodready/regression/``. Run them once before the fix (the
ones tied to a finding must fail) and again after it (everything must pass).

What it writes:
  prodready_guard.py                   stack-independent, standard library only. Re-scans the app and fails if any
                                       finding it was generated from comes back. Also runs in CI.
  ProdreadyRouteContractTest.php       Laravel. Every route that existed when the tests were generated must still
                                       exist, with the same HTTP method and, if it was protected, an auth middleware.
                                       This catches a fix that deleted or loosened a route.
  ProdreadyFindingsTest.php            Laravel. Behaviour tests for findings that can be checked through HTTP:
                                       unauthenticated access (AUTH-002), rate limits (API-020), other users' records
                                       (API-021).
  prodready.regression.test.mjs        Node. Unauthenticated access tests (AUTH-002) for JavaScript servers,
                                       using node:test and fetch against BASE_URL.
  README.md                            How to run them.

What it deliberately does not do: it does not run the tests, does not touch the app's own files unless
``--into-app`` is given, and does not invent business rules. Behaviour tests contain an arrange step built
from model factories; if your factories need more fields, adjust that step. Tests it cannot build for a
finding are left to the guard.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from typing import Any, Dict, List, Optional

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from lib import catalog, findings, phpscan, walker  # noqa: E402

IMPLEMENTS: List[str] = []
ALSO_EMITS: List[str] = []

ROUTE_SUBJECT = re.compile(r"^(GET|POST|PUT|PATCH|DELETE) (/\S*)$")


def _php(value: Any) -> str:
    """A PHP literal for strings, bools, ints and lists of those."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_php(v) for v in value) + "]"
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def _concrete(uri: str) -> str:
    return re.sub(r"\{[^}]+\}", "1", uri)


def select(doc: Dict[str, Any], only: List[str], min_severity: str) -> List[Dict[str, Any]]:
    floor = findings.severity_rank(min_severity)
    out = []
    for f in doc["findings"]:
        if f.get("status") == "ignored" or findings.severity_rank(f["severity"]) < floor:
            continue
        if only and not any(f["check_id"] == o or f["check_id"].split("-")[0] == o for o in only):
            continue
        out.append(f)
    return out


def guard_source(selected: List[Dict[str, Any]], scripts_dir: str, app_rel: str) -> str:
    fixed = [{"check_id": f["check_id"], "file": f.get("file"), "line": f.get("line"), "fingerprint": f["fingerprint"], "message": f["message"][:160]} for f in selected]
    return '''#!/usr/bin/env python3
"""Generated by prodready %(version)s. Fails if a finding that was fixed comes back.

Run before the fix: it must fail. Run after the fix: it must pass. Standard library only.
Set PRODREADY_SCRIPTS to the folder that holds run_all.py if prodready lives somewhere else.
"""
import json
import os
import subprocess
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.environ.get("PRODREADY_SCRIPTS") or %(scripts)r
APP = os.environ.get("PRODREADY_APP") or os.path.normpath(os.path.join(HERE, %(app)r))
TRACKED = json.loads(%(tracked)r)


class FixedFindingsStayFixed(unittest.TestCase):
    def test_no_tracked_finding_returns(self):
        run_all = os.path.join(SCRIPTS, "run_all.py")
        if not os.path.isfile(run_all):
            self.skipTest("prodready scripts not found at %%s; set PRODREADY_SCRIPTS" %% SCRIPTS)
        proc = subprocess.run([sys.executable, run_all, APP, "--quiet"], capture_output=True, text=True, encoding="utf-8")
        self.assertEqual(proc.returncode, 0, proc.stderr[-400:])
        current = {f["fingerprint"] for f in json.loads(proc.stdout)["findings"] if f.get("status") != "ignored"}
        back = [t for t in TRACKED if t["fingerprint"] in current]
        self.assertEqual(back, [], "%%d finding(s) still present or back: %%s" %% (len(back), "; ".join("%%s %%s:%%s" %% (b["check_id"], b["file"], b["line"]) for b in back[:8])))


if __name__ == "__main__":
    unittest.main()
''' % {"version": findings.__version__, "scripts": scripts_dir, "app": app_rel, "tracked": json.dumps(fixed)}


def route_contract_php(project: walker.Project) -> Optional[str]:
    routes = phpscan.route_inventory(project)
    rows = []
    seen = set()
    for r in routes:
        if r["method"] in ("ANY",) or (r["method"], r["uri"]) in seen or r["uri"].startswith("/up"):
            continue
        seen.add((r["method"], r["uri"]))
        rows.append([r["method"], r["uri"], bool(r["auth"])])
    if not rows:
        return None
    data = ",\n            ".join("[%s, %s, %s]" % (_php(m), _php(u), _php(a)) for m, u, a in rows)
    return '''<?php

namespace Tests\\Feature;

use Illuminate\\Support\\Facades\\Route;
use PHPUnit\\Framework\\Attributes\\DataProvider;
use Tests\\TestCase;

/**
 * Generated by prodready %(version)s. Every route that existed when this file was generated must still exist
 * with the same method, and keep an authentication middleware if it had one. Regenerate it after you add
 * routes on purpose.
 */
class ProdreadyRouteContractTest extends TestCase
{
    public static function routes(): array
    {
        return [
            %(data)s,
        ];
    }

    private function normalise(string $uri): string
    {
        return '/' . trim(preg_replace('/\\{[^}]+\\}/', '{}', $uri), '/');
    }

    #[DataProvider('routes')]
    public function test_route_still_exists_with_its_protection(string $method, string $uri, bool $needsAuth): void
    {
        $found = null;
        foreach (Route::getRoutes() as $route) {
            if ($this->normalise($route->uri()) === $this->normalise($uri) && in_array($method, $route->methods(), true)) {
                $found = $route;
                break;
            }
        }

        $this->assertNotNull($found, "$method $uri no longer exists");

        if ($needsAuth) {
            $protected = collect($found->gatherMiddleware())->contains(
                fn ($m) => is_string($m) && (str_starts_with($m, 'auth') || str_starts_with($m, 'can:') || $m === 'verified' || str_starts_with($m, 'role'))
            );
            $this->assertTrue($protected, "$method $uri lost its authentication middleware");
        }
    }
}
''' % {"version": findings.__version__, "data": data}


def findings_php(selected: List[Dict[str, Any]], project: walker.Project) -> Optional[str]:
    comp = phpscan.composer(project)
    sanctum = "laravel/sanctum" in comp["require"]
    guard = ", 'sanctum'" if sanctum else ""
    unauth, throttle, owner = [], [], []
    seen = set()
    for f in selected:
        m = ROUTE_SUBJECT.match((f.get("subject") or {}).get("name") or "")
        if not m:
            continue
        key = (f["check_id"], m.group(1), m.group(2))
        if key in seen:
            continue
        seen.add(key)
        if f["check_id"] == "AUTH-002":
            unauth.append((m.group(1), m.group(2)))
        elif f["check_id"] == "API-020":
            throttle.append((m.group(1), m.group(2)))
        elif f["check_id"] == "API-021":
            mm = re.search(r"binds `(\w+)`", f.get("detail") or "")
            owner.append((m.group(1), m.group(2), mm.group(1) if mm else ""))
    if not (unauth or throttle or owner):
        return None
    body = []
    for i, (verb, uri) in enumerate(unauth, 1):
        body.append('''    public function test_unauthenticated_%(i)d_%(slug)s_is_refused(): void
    {
        $response = $this->json(%(verb)s, %(uri)s);

        $this->assertContains($response->getStatusCode(), [401, 403, 302, 419], %(msg)s . $response->getStatusCode());
    }
''' % {"i": i, "slug": re.sub(r"\W+", "_", verb.lower() + uri).strip("_"), "verb": _php(verb), "uri": _php(_concrete(uri)), "msg": _php("%s %s answered without signing in: " % (verb, uri))})
    for i, (verb, uri) in enumerate(throttle, 1):
        body.append('''    public function test_rate_limit_%(i)d_%(slug)s(): void
    {
        $last = 0;
        for ($n = 0; $n < 30; $n++) {
            $last = $this->json(%(verb)s, %(uri)s, ['email' => 'nobody@example.com', 'password' => 'wrong-password'])->getStatusCode();
            if ($last === 429) {
                break;
            }
        }

        $this->assertSame(429, $last, %(msg)s);
    }
''' % {"i": i, "slug": re.sub(r"\W+", "_", verb.lower() + uri).strip("_"), "verb": _php(verb), "uri": _php(_concrete(uri)), "msg": _php("%s %s was never rate limited in 30 requests" % (verb, uri))})
    for i, (verb, uri, model) in enumerate(owner, 1):
        if not model:
            continue
        body.append('''    public function test_other_users_record_is_not_reachable_%(i)d_%(slug)s(): void
    {
        $class = '\\\\App\\\\Models\\\\' . %(model)s;
        if (! class_exists($class) || ! method_exists($class, 'factory') || ! method_exists(\\App\\Models\\User::class, 'factory')) {
            $this->markTestSkipped('needs model factories for User and ' . %(model)s);
        }

        $owner = \\App\\Models\\User::factory()->create();
        $intruder = \\App\\Models\\User::factory()->create();
        // Arrange: a record that belongs to $owner. Add owner or tenant columns here if your factory needs them.
        $record = $class::factory()->create();
        $uri = preg_replace('/\\{[^}]+\\}/', (string) $record->getKey(), %(uri)s, 1);

        $this->actingAs($intruder%(guard)s);
        $response = $this->json(%(verb)s, $uri);

        $this->assertContains($response->getStatusCode(), [403, 404], %(msg)s . $response->getStatusCode());
    }
''' % {"i": i, "slug": re.sub(r"\W+", "_", verb.lower() + uri).strip("_"), "verb": _php(verb), "uri": _php(uri), "model": _php(model), "guard": guard, "msg": _php("%s %s let another user reach a record: " % (verb, uri))})
    return '''<?php

namespace Tests\\Feature;

use Illuminate\\Foundation\\Testing\\RefreshDatabase;
use Tests\\TestCase;

/**
 * Generated by prodready %(version)s from the scan findings. Run it before the fix (these tests must fail)
 * and after it (they must pass). Review the arrange steps; they are a starting point.
 */
class ProdreadyFindingsTest extends TestCase
{
    use RefreshDatabase;

%(body)s}
''' % {"version": findings.__version__, "body": "\n".join(body)}


def node_test(selected: List[Dict[str, Any]]) -> Optional[str]:
    routes = []
    for f in selected:
        if f["check_id"] != "AUTH-002":
            continue
        m = ROUTE_SUBJECT.match((f.get("subject") or {}).get("name") or "")
        if m and (m.group(1), _concrete(m.group(2))) not in routes:
            routes.append((m.group(1), _concrete(m.group(2))))
    if not routes:
        return None
    rows = ",\n  ".join("[%s, %s]" % (json.dumps(v), json.dumps(u)) for v, u in routes)
    return '''// Generated by prodready %(version)s. Run before the fix (must fail) and after it (must pass).
// Start your app, then:  BASE_URL=http://localhost:3000 node --test prodready.regression.test.mjs
import { test } from "node:test";
import assert from "node:assert/strict";

const BASE_URL = process.env.BASE_URL || "http://localhost:3000";
const routes = [
  %(rows)s,
];

for (const [method, path] of routes) {
  test(`${method} ${path} refuses a request with no credentials`, async () => {
    const res = await fetch(BASE_URL + path, { method, redirect: "manual", headers: { "content-type": "application/json" }, body: method === "GET" ? undefined : "{}" });
    assert.ok([301, 302, 303, 307, 308, 401, 403].includes(res.status), `${method} ${path} answered ${res.status} without credentials`);
  });
}
''' % {"version": findings.__version__, "rows": rows}


