"""PHPUnit templates: policies exercised on real users and records, and double spending with real parallel processes."""
from __future__ import annotations

import re
from typing import Any, List, Optional, Tuple

from . import findings, phpscan, walker

RECORD_ABILITIES = ("view", "update", "delete", "restore", "forceDelete")
OWNER_COLUMNS = ("user_id", "owner_id", "created_by", "author_id", "company_id", "team_id", "tenant_id", "organization_id")


def _php(value: Any) -> str:
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


