def _owner_column(project: walker.Project, model_pf: phpscan.PhpFile) -> str:
    table = phpscan.table_of(model_pf)
    for pf in phpscan.php_files(project):
        if "/migrations/" not in "/" + pf.rel:
            continue
        m = re.search(r"Schema::create\(\s*['\"]%s['\"]" % re.escape(table), pf.code)
        if m:
            open_idx = pf.bare.find("{", m.end())
            body = pf.code[open_idx:phpscan.match_brace(pf.bare, open_idx)]
            for col in OWNER_COLUMNS:
                if re.search(r"['\"]%s['\"]" % col, body):
                    return col
    return "user_id"


def policy_php(project: walker.Project) -> Optional[str]:
    models = phpscan.model_class_names(project)
    body: List[str] = []
    for pf in phpscan.php_files(project):
        if not (pf.rel.startswith("app/Policies/") and pf.class_name.endswith("Policy")):
            continue
        model = pf.class_name[:-6]
        if model not in models:
            continue
        col = _owner_column(project, models[model])
        by_user = col in ("user_id", "owner_id", "created_by", "author_id")
        for m in pf.methods():
            if m["name"] not in RECORD_ABILITIES or len(re.findall(r"\$\w+", m["params"])) < 2:
                continue
            body.append(POLICY_TEST % {
                "slug": "%s_%s_allows_the_owner_and_denies_others" % (model.lower(), m["name"].lower()), "model": _php(model), "ability": _php(m["name"]), "ability_text": m["name"],
                "col": _php(col), "owner_value": "$owner->id" if by_user else "1",
                "owner_attrs": "" if by_user else "[%s => 1]" % _php(col), "other_attrs": "" if by_user else "[%s => 2]" % _php(col)})
    if not body:
        return None
    return POLICY_HEAD % {"version": findings.__version__, "body": "\n".join(body)}


def concurrency_php(project: walker.Project, rows: List[Tuple[str, bool]], wallet: str, field: str, n: int = 8) -> Optional[str]:
    if "laravel/sanctum" not in phpscan.composer(project)["require"] or not rows:
        return None
    body = [CONC_TEST % {"i": i, "slug": re.sub(r"\W+", "_", uri.lower()).strip("_"), "wallet": _php(wallet), "field": _php(field), "uri": _php(uri), "n": n} for i, (uri, _) in enumerate(rows[:4], 1)]
    return CONC_HEAD % {"version": findings.__version__, "n": n, "body": "\n".join(body)}


def money_context(project: walker.Project):
    models = phpscan.model_class_names(project)
    wallet = next((n for n, pf in models.items() if "balance" in pf.code or "credits" in pf.code), None)
    if not wallet:
        return None
    field = "balance" if "balance" in models[wallet].code else "credits"
    pat = re.compile("transfer|withdraw|payout|pay|send|spend|redeem|purchase|checkout", re.I)
    rows = [(r["uri"], False) for r in phpscan.route_inventory(project) if r["method"] == "POST" and pat.search(r["uri"]) and "webhook" not in r["uri"].lower()]
    return wallet, field, rows
