#!/usr/bin/env python3
"""Check the code that runs in the browser or on the device.

Detects: user-controlled content inserted as HTML (FE-001), sensitive data
and session tokens kept in browser storage (FE-002, AUTH-006), debug output
(FE-003), missing error boundaries (FE-004), third-party scripts without
integrity (FE-007), basic accessibility gaps (FE-008), unsafe new-tab links
(FE-009), trackers that load without consent (PRIV-002), session replay that
captures inputs (PRIV-007), whole tables fetched and filtered in the client
(PERF-002), oversized images and bundles (PERF-003, PERF-004), listeners that
are never cleaned up (PERF-006), and the launch polish items that visitors
notice first: default metadata, default icons, placeholder content and
builder branding (LAUNCH-001, LAUNCH-002, LAUNCH-004, LAUNCH-005).

What it deliberately does not do: it does not render the app, so it cannot
see runtime behaviour, contrast or layout. Default favicons are recognised by
file name and reference, not by image comparison.
"""
from __future__ import annotations

import os
import re
import sys
from typing import Any, Dict, List, Optional

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import detect_stack  # noqa: E402
from lib import catalog, findings, jsast, patterns, walker  # noqa: E402
from lib.findings import Envelope, Finding  # noqa: E402

IMPLEMENTS = catalog.by_scanner("scan_frontend")
ALSO_EMITS: List[str] = []

UI_EXTS = {".tsx", ".jsx", ".vue", ".svelte", ".astro", ".html", ".js", ".ts"}
HTML_SINK_RE = re.compile(
    r"dangerouslySetInnerHTML\s*=\s*\{\s*\{\s*__html\s*:\s*(?P<a>[^}]+)\}|v-html\s*=\s*\"(?P<b>[^\"]+)\"|\{@html\s+(?P<c>[^}]+)\}|"
    r"\.(?:innerHTML|outerHTML)\s*=\s*(?P<d>[^;\n]+)|document\.write\(\s*(?P<e>[^)\n]+)|insertAdjacentHTML\(\s*[^,]+,\s*(?P<f>[^)\n]+)|"
    r"bypassSecurityTrust\w+\(\s*(?P<g>[^)\n]+)"
)
DEFAULT_TITLES = {"vite + react", "vite + react + ts", "vite app", "react app", "create next app", "lovable app", "lovable-generated-project", "v0 app", "my v0 project", "new remix app", "welcome to remix", "create t3 app", "vite + vue", "vite + svelte", "expo app", "document", "bolt app", "replit"}
DEFAULT_DESCRIPTIONS = ("generated by create next app", "lovable generated project", "web site created using create-react-app", "created with v0", "generated by v0")
TRACKERS = {
    "google-analytics": r"googletagmanager\.com|google-analytics\.com|\bgtag\(", "facebook-pixel": r"connect\.facebook\.net|\bfbq\(",
    "hotjar": r"static\.hotjar\.com|\bhj\(", "clarity": r"clarity\.ms", "tiktok-pixel": r"analytics\.tiktok\.com",
    "linkedin-insight": r"snap\.licdn\.com", "segment": r"cdn\.segment\.com", "mixpanel": r"cdn\.mxpnl\.com|mixpanel\.init\(",
    "fullstory": r"fullstory\.com/s/fs\.js|FullStory\.init\(", "logrocket": r"LogRocket\.init\(|cdn\.lr-ingest\.io",
}
CONSENT_RE = re.compile(r"(?i)consent|cookie-?banner|cookiebot|onetrust|klaro|cookieyes|iubenda|termly|usercentrics|osano")
CDN_HOSTS_RE = re.compile(r"(?i)cdn\.jsdelivr\.net|unpkg\.com|cdnjs\.cloudflare\.com|cdn\.tailwindcss\.com|code\.jquery\.com|polyfill\.io|cdn\.gpteng\.co|ajax\.googleapis\.com|stackpath\.bootstrapcdn\.com|esm\.sh|cdn\.skypack\.dev")
SRI_EXEMPT_RE = re.compile(r"(?i)js\.stripe\.com|challenges\.cloudflare\.com|google\.com/recaptcha|accounts\.google\.com|googletagmanager\.com|connect\.facebook\.net|static\.hotjar\.com|clarity\.ms|paypal\.com/sdk|plausible\.io|cdn\.paddle\.com|maps\.googleapis\.com")
HEAVY_IMPORTS = {"lodash": "import the functions you use from lodash-es or lodash/<name>", "moment": "use date-fns or dayjs", "aws-sdk": "use the modular @aws-sdk/client-* packages", "firebase/compat/app": "use the modular firebase/* imports"}
PLACEHOLDER_RES = [
    (re.compile(r"(?i)lorem ipsum"), "placeholder text (lorem ipsum)"),
    (re.compile(r"\b(?:John|Jane) Doe\b"), "placeholder person name"),
    (re.compile(r"(?i)\bcoming soon\b"), "\"coming soon\" text"),
    (re.compile(r"(?i)\b(?:TODO|FIXME)\b[: ]"), "TODO text visible to users"),
    (re.compile(r"\b[\w.+-]+@example\.com\b"), "example.com email address"),
]
STORAGE_SET_RE = re.compile(r"\b(?P<store>localStorage|sessionStorage|AsyncStorage)\.setItem\(\s*(?P<key>[\"'`][^\"'`]*[\"'`]|\w+)\s*,\s*(?P<val>[^;\n]+)")
TOKEN_KEY_RE = re.compile(r"(?i)token|jwt|session|auth|bearer|access|refresh|id_?token|credential")
PII_KEY_RE = re.compile(r"(?i)user|profile|account|email|phone|address|card|customer|patient|member")
REPLAY_RES = [
    (re.compile(r"LogRocket\.init\(([^)]*)\)"), r"sanitiz|inputSanitizer|dom\s*:", "LogRocket"),
    (re.compile(r"FullStory\.init\(([^)]*)\)|\bFS\.init\("), r"mask|exclude", "FullStory"),
    (re.compile(r"rrweb\.record\(([^)]*)\)"), r"maskAllInputs\s*:\s*true", "rrweb"),
    (re.compile(r"smartlook\(\s*[\"']init"), r"mask", "Smartlook"),
]
REPLAY_OFF_RE = re.compile(r"(?:maskAllInputs|mask_all_inputs|maskAllText|maskInputs)\s*:\s*false")


def _ui_text_spans(src: str) -> List[re.Match]:
    """Matches of user-visible text: JSX or HTML text nodes and common string props."""
    return list(re.finditer(r">\s*([^<>{}\n]{3,200}?)\s*<|\b(?:title|placeholder|alt|label|aria-label|content|description|text|name)\s*[=:]\s*[\"']([^\"'\n]{3,200})[\"']", src))


def scan(root: str, stack: Optional[Dict[str, Any]], project: walker.Project) -> Envelope:
    env = Envelope("scan_frontend", stack)
    fw = project.framework
    deps = project.deps
    is_web = detect_stack.is_web(stack)
    is_mobile = bool((stack or {}).get("mobile"))
    if not is_web and not is_mobile and not any(sf.ext in (".tsx", ".jsx", ".vue", ".svelte", ".html") for sf in project.files):
        env.inventory["frontend"] = {"detected": False}
        return env
    consent_present = any(re.search(CONSENT_RE, d) for d in deps)
    tracker_inv: Dict[str, List[str]] = {}
    script_inv: List[Dict[str, Any]] = []
    custom_auth = not (detect_stack.has(stack, "auth", "supabase-auth", "firebase-auth", "clerk", "auth0", "authjs", "better-auth", "kinde", "workos"))
    alt_missing: List[tuple] = []
    div_click: List[tuple] = []
    has_error_boundary = False
    has_catch_all = False
    all_ui_text: List[str] = []

    ui_files = [sf for sf in project.files if sf.ext in UI_EXTS and project.classify(sf) in ("client", "shared", "server") and not sf.minified]
    for sf in ui_files:
        text = project.text(sf)
        if not text or project.classify(sf) == "test":
            continue
        rel = sf.rel
        kind = project.classify(sf)
        is_markup = sf.ext in (".tsx", ".jsx", ".vue", ".svelte", ".astro", ".html")
        if sf.ext == ".html":
            src = re.sub(r"<!--[\s\S]*?-->", lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)
            code = src
        else:
            lx = jsast.lexed(text)
            src, code = lx.nocomment, lx.code
        if not consent_present and CONSENT_RE.search(text):
            consent_present = True
        if re.search(r"ErrorBoundary|componentDidCatch|errorElement|onErrorCaptured|react-error-boundary|handleError\s*:", text) or re.search(r"(^|/)(error|global-error)\.[jt]sx?$|\+error\.svelte$", rel):
            has_error_boundary = True
        if re.search(r"path\s*=\s*[\"']\*[\"']|path\s*:\s*[\"']\*[\"']|(^|/)not-found\.[jt]sx?$|(^|/)404\.[jt]sx?$|\[\.\.\.\w+\]", text + " " + rel):
            has_catch_all = True

        # FE-001: HTML sinks (model-output sinks are reported by scan_llm as LLM-006).
        if kind != "server" or is_markup:
            for m in HTML_SINK_RE.finditer(src):
                expr = next(g for g in m.groupdict().values() if g).strip()
                if re.match(r"^[\"'`][^$]*[\"'`]$", expr) or patterns.HTML_SANITIZER_RE.search(expr):
                    continue
                before = src[max(0, m.start() - 120):m.start()]
                if re.search(r"<style\b[^>]*$|<script[^>]*type\s*=\s*[\"']application/ld\+json[\"'][^>]*$", before):
                    continue
                if patterns.is_llm_output_sink(text, expr):
                    continue
                line = jsast.line_of(src, m.start())
                env.add(Finding(
                    "FE-001", "Content that users can write is inserted into the page as live HTML. Someone can post a script that then runs in every other visitor's browser, with their session.",
                    file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                    detail="HTML sink receives `%s`, which is not a constant and is not passed through a sanitiser." % expr,
                    fix_hint="Render it as text. If HTML is required, sanitise it with a maintained sanitiser such as DOMPurify before inserting it.",
                ))

        # FE-002 and AUTH-006: browser storage.
        if kind != "server":
            for m in STORAGE_SET_RE.finditer(src):
                key = m.group("key").strip("\"'`")
                val = m.group("val")
                line = jsast.line_of(src, m.start())
                if TOKEN_KEY_RE.search(key) or re.search(r"(?i)\b(?:access_?token|refresh_?token|id_?token|jwt)\b", val):
                    if custom_auth or re.search(r"(?i)getIdToken|access_token|refresh_token|session\.", val + src[max(0, m.start() - 300):m.start()]):
                        env.add(Finding(
                            "AUTH-006", "The login token is saved where any script on the page%s can read it. One injected script or one browser extension is enough to take over the account." % (" or any app on a rooted device" if m.group("store") == "AsyncStorage" else ""),
                            file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                            detail="%s.setItem('%s', ...) stores a session or access token in plain storage." % (m.group("store"), key),
                            fix_hint="Use HttpOnly, Secure, SameSite cookies set by the server on the web, and the platform's secure storage on mobile.",
                        ))
                elif PII_KEY_RE.search(key) and re.search(r"JSON\.stringify|user|profile|data", val):
                    env.add(Finding(
                        "FE-002", "A copy of the user's personal data is kept in the browser's storage, where it stays after sign-out and is readable by any script on the page.",
                        file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                        detail="%s.setItem('%s', ...) persists a user record." % (m.group("store"), key),
                        fix_hint="Store the minimum needed, and clear it on sign-out.",
                    ))
            if re.search(r"\bpersist\(\s*(?:\(|\w)", code) and "partialize" not in code and re.search(r"zustand|redux-persist", text):
                m = re.search(r"\bpersist\(", code)
                line = jsast.line_of(code, m.start())
                env.add(Finding(
                    "FE-002", "The whole app state is saved to browser storage, including whatever user data it holds.",
                    file=rel, line=line, snippet=sf.line_text(line), confidence="possible",
                    detail="State persistence without a partialize/whitelist option.",
                    fix_hint="Persist only the keys that need to survive a reload.",
                ))

        # FE-003: debug output.
        if kind == "client" and sf.ext != ".html":
            logs = [m for m in re.finditer(r"\bconsole\.(?:log|debug|dir|table)\(|\bdebugger\s*;", code)]
            if logs:
                line = jsast.line_of(code, logs[0].start())
                env.add(Finding(
                    "FE-003", "Debug output is left in the app. Anyone who opens the browser console sees it, and it can include user data.",
                    file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                    detail="%d console or debugger statement(s) in this file." % len(logs),
                    fix_hint="Remove them or strip them at build time.",
                ))

        # FE-007 and script inventory; PRIV-002 tracker inventory.
        for m in re.finditer(r"<[sS]cript\b([^>]*)>", src):
            attrs = m.group(1)
            sm = re.search(r"\bsrc\s*=\s*[\"'{]\s*[\"'`]?(https?://[^\"'`\s}]+)", attrs)
            if not sm:
                continue
            url = sm.group(1)
            line = jsast.line_of(src, m.start())
            has_sri = bool(re.search(r"\bintegrity\s*=", attrs))
            script_inv.append({"file": rel, "line": line, "src": url.split("?")[0], "integrity": has_sri})
            if not has_sri and not SRI_EXEMPT_RE.search(url):
                known_cdn = bool(CDN_HOSTS_RE.search(url))
                env.add(Finding(
                    "FE-007", "The page loads a script from another company's server with no integrity check. If that server is compromised, the attacker's code runs on your site with full access to the page.",
                    file=rel, line=line, snippet=sf.line_text(line), confidence="likely" if known_cdn else "possible",
                    detail="<script src=\"%s\"> has no integrity attribute.%s" % (url.split("?")[0], " polyfill.io was compromised in 2024 and should be removed." if "polyfill.io" in url else ""),
                    fix_hint="Self-host the file, or pin an exact version with an integrity hash and crossorigin=\"anonymous\". Remove scripts the page does not need.",
                ))
        for name, rx in TRACKERS.items():
            tm = re.search(rx, src)
            if tm:
                tracker_inv.setdefault(name, []).append("%s:%d" % (rel, jsast.line_of(src, tm.start())))

        # PRIV-007: session replay capturing inputs.
        if kind != "server":
            om = REPLAY_OFF_RE.search(src)
            if om:
                line = jsast.line_of(src, om.start())
                env.add(Finding(
                    "PRIV-007", "Session recording is set to capture what users type. Passwords, card details and private messages end up in a third party's recordings.",
                    file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                    detail="Input masking is explicitly disabled: `%s`." % om.group(0),
                    fix_hint="Mask all inputs by default and exclude sensitive pages from recording.",
                ))
            else:
                for rx, ok, name in REPLAY_RES:
                    rm = rx.search(src)
                    if rm and not re.search(ok, rm.group(0)):
                        line = jsast.line_of(src, rm.start())
                        env.add(Finding(
                            "PRIV-007", "%s session recording is switched on without input masking configured. Depending on its defaults, what users type may be recorded." % name,
                            file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                            detail="%s initialised with no sanitising or masking options." % name,
                            fix_hint="Configure input and network sanitising, and exclude sign-in and payment pages.",
                        ))
                        break

        # PERF-002: whole tables fetched and filtered in the client.
        if kind == "client":
            for m in re.finditer(r"\.from\(\s*[\"'`]([\w.]+)[\"'`]\s*\)\s*\.select\(\s*(?:[\"'`]\*[\"'`])?\s*\)|getDocs\(\s*collection\(\s*\w+\s*,\s*[\"'`]([\w/]+)[\"'`]\s*\)\s*\)", src):
                chain = re.match(r"(?:\s*\.\w+\([^()]*(?:\([^()]*\)[^()]*)*\))*", code[m.end():])
                if chain and re.search(r"\.(?:eq|neq|limit|range|single|maybeSingle|match|in|lt|gt|lte|gte|textSearch|filter|or|ilike|like|contains)\(", chain.group(0)):
                    continue
                after = code[m.end(): m.end() + 900]
                fm = re.search(r"\.(?:filter|find|sort|slice)\(", after)
                if fm:
                    line = jsast.line_of(src, m.start())
                    env.add(Finding(
                        "PERF-002", "The app downloads the whole `%s` table to the browser and then picks out what it needs. That is slow, costs money, and hands every visitor rows they should not receive." % (m.group(1) or m.group(2)),
                        file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                        detail="Unfiltered fetch followed by client-side .%s within the same component." % fm.group(0).strip(".("),
                        fix_hint="Filter, sort and paginate in the query, and let the access rules return only the caller's rows.",
                    ))
                    break

        # PERF-004: heavy libraries imported whole in client code.
        if kind == "client" and sf.ext != ".html":
            for imp in jsast.find_imports(text):
                advice = HEAVY_IMPORTS.get(imp.spec)
                whole_icons = imp.namespace and re.search(r"^(lucide-react|react-icons(/.*)?|@mui/icons-material|@heroicons/react.*|@tabler/icons-react)$", imp.spec)
                if (advice and (imp.default or imp.namespace)) or whole_icons:
                    env.add(Finding(
                        "PERF-004", "A large library is loaded in full for every visitor, which slows the first page load on phones.",
                        file=rel, line=imp.line, snippet=sf.line_text(imp.line), confidence="likely",
                        detail="`%s` is imported wholesale in client code. %s." % (imp.spec, (advice or "import individual icons by name").capitalize()),
                        fix_hint="Import only what is used, or load the feature with a dynamic import.",
                    ))
                    break

        # PERF-006: subscriptions never cleaned up.
        if kind != "server" and "useEffect" in code:
            for call in jsast.find_calls(text, ["useEffect", "React.useEffect"]):
                body = call.args
                sm = re.search(r"onSnapshot\(|\.subscribe\(|\.on\(\s*[\"']postgres_changes|new\s+WebSocket\(|onAuthStateChange\(|onValue\(|setInterval\(|addEventListener\(", body)
                if sm and not re.search(r"\breturn\b", jsast.lexed(body).code):
                    line = call.line + body[: sm.start()].count("\n")
                    env.add(Finding(
                        "PERF-006", "A live data subscription is opened every time this screen appears and never closed. Over time that means duplicate updates, memory leaks and rising costs.",
                        file=rel, line=line, snippet=sf.line_text(line), confidence="likely",
                        detail="useEffect starts `%s` and returns no cleanup function." % sm.group(0).strip("("),
                        fix_hint="Return a cleanup function from the effect that unsubscribes, and narrow the listener's query.",
                    ))
                    break

        # FE-008, FE-009, LAUNCH-004 in markup.
        if is_markup:
            for m in re.finditer(r"<img\b([^>]*)>", src):
                if not re.search(r"\balt\s*=", m.group(1)):
                    alt_missing.append((rel, jsast.line_of(src, m.start())))
            for m in re.finditer(r"<(?:div|span)\b[^>]*\bon[Cc]lick\s*=", src):
                if not re.search(r"role\s*=|tabIndex", m.group(0)):
                    div_click.append((rel, jsast.line_of(src, m.start())))
            blanks = [m for m in re.finditer(r"<a\b[^>]*target\s*=\s*[\"']_blank[\"'][^>]*>", src) if not re.search(r"\brel\s*=\s*[\"'][^\"']*noopener", m.group(0))]
            if blanks:
                line = jsast.line_of(src, blanks[0].start())
                env.add(Finding(
                    "FE-009", "Links that open a new tab do not isolate it from your page. Older browsers let the new page redirect yours.",
                    file=rel, line=line, snippet=sf.line_text(line), confidence="possible",
                    detail="%d link(s) with target=\"_blank\" and no rel=\"noopener\". Current browsers apply noopener by default; older ones do not." % len(blanks),
                    fix_hint="Add rel=\"noopener noreferrer\".",
                ))
            if kind != "server" or fw == "nextjs":
                hits = []
                for tm in _ui_text_spans(src):
                    chunk = tm.group(1) or tm.group(2) or ""
                    all_ui_text.append(chunk)
                    for rx, label in PLACEHOLDER_RES:
                        if rx.search(chunk):
                            hits.append((jsast.line_of(src, tm.start()), label))
                            break
                for sm in re.finditer(r"(?:text|quote|body|description|title|name)\s*:\s*[\"']([^\"'\n]{3,200})[\"']", src):
                    for rx, label in PLACEHOLDER_RES[:2]:
                        if rx.search(sm.group(1)):
                            hits.append((jsast.line_of(src, sm.start()), label))
                dead = re.search(r"on[Cc]lick\s*=\s*\{\s*\(\s*\)\s*=>\s*\{\s*\}\s*\}|href\s*=\s*[\"']#[\"']", src)
                if dead:
                    hits.append((jsast.line_of(src, dead.start()), "a button or link that does nothing"))
                mock = re.search(r"\b(?:const|let)\s+(?:mock|fake|dummy|sample)\w*\s*=\s*\[|\bMOCK_\w+\s*=", code)
                if mock:
                    hits.append((jsast.line_of(code, mock.start()), "hard-coded mock data"))
                if hits:
                    hits.sort()
                    labels = sorted({h[1] for h in hits})
                    env.add(Finding(
                        "LAUNCH-004", "Placeholder content is still in the app: %s. Visitors read this as an unfinished or untrustworthy product." % ", ".join(labels),
                        file=rel, line=hits[0][0], snippet=sf.line_text(hits[0][0]), confidence="likely",
                        detail="%d placeholder item(s) in user-visible text in this file." % len(hits),
                        fix_hint="Replace with real content or remove it. Invented testimonials and statistics should be deleted, not reworded.",
                    ))

    # --- project-level frontend checks --------------------------------------
    index = project.get("index.html") or project.get("public/index.html")
    layout = next((project.get(p) for p in ("app/layout.tsx", "src/app/layout.tsx", "app/layout.jsx", "src/app/layout.jsx", "app/layout.js") if project.get(p)), None)
    head_file = index or layout
    head_text = project.text(head_file) if head_file else ""

    # LAUNCH-001: metadata.
    if head_file and is_web:
        title = None
        tm = re.search(r"<title>([^<]*)</title>", head_text) or re.search(r"\btitle\s*:\s*[\"'`]([^\"'`]+)[\"'`]", head_text)
        if tm:
            title = tm.group(1).strip()
        desc = re.search(r"name=[\"']description[\"'][^>]*content=[\"']([^\"']*)[\"']|\bdescription\s*:\s*[\"'`]([^\"'`]+)[\"'`]", head_text)
        desc_text = (desc.group(1) or desc.group(2) or "").strip() if desc else ""
        problems = []
        line = 1
        if title is None:
            problems.append("no page title")
        elif title.lower() in DEFAULT_TITLES:
            problems.append("the title is still the template default (\"%s\")" % title)
            line = head_text.count("\n", 0, tm.start()) + 1
        if not desc_text:
            problems.append("no description")
        elif desc_text.lower() in DEFAULT_DESCRIPTIONS:
            problems.append("the description is the template default")
        if "lovable.dev/opengraph" in head_text:
            problems.append("the social preview image is the builder's default")
        elif not re.search(r"og:image|openGraph|opengraph-image|twitter:image", head_text) and not any(re.search(r"opengraph-image\.", p) for p in project.all_paths()):
            problems.append("no social preview image")
        if problems:
            env.add(Finding(
                "LAUNCH-001", "When someone shares a link to the app, it shows up with %s." % "; ".join(problems),
                file=head_file.rel, line=line, snippet=head_file.line_text(line), confidence="confirmed" if any("default" in p for p in problems) else "likely",
                detail="Page metadata in %s: %s." % (head_file.rel, "; ".join(problems)),
                fix_hint="Set a real title, description, canonical URL and social image.",
            ))

    # LAUNCH-002: icons and manifest.
    if is_web:
        paths = project.all_paths()
        problems = []
        icon_ref = re.search(r"rel=[\"'](?:shortcut )?icon[\"'][^>]*href=[\"']([^\"']+)[\"']", head_text)
        default_names = ("vite.svg", "next.svg", "vercel.svg", "logo192.png", "react.svg", "placeholder.svg")
        if icon_ref and icon_ref.group(1).split("/")[-1] in default_names:
            problems.append("the browser tab icon is the template default (%s)" % icon_ref.group(1))
        has_icon = bool(icon_ref) or any(re.search(r"(^|/)(favicon\.(ico|png|svg)|icon\.(png|svg|ico|tsx?)|apple-icon\.\w+)$", p) for p in paths)
        if not has_icon:
            problems.append("no browser tab icon")
        if not re.search(r"apple-touch-icon", head_text) and not any(re.search(r"apple-(touch-)?icon", p) for p in paths) and not any(re.search(r"(^|/)app/icon\.", p) for p in paths):
            problems.append("no home-screen icon")
        if not any(re.search(r"manifest\.(json|webmanifest|ts|js)$", p) for p in paths):
            problems.append("no web app manifest")
        default_icon = any("default" in p for p in problems)
        if default_icon or len(problems) >= 2:
            line = head_text.count("\n", 0, icon_ref.start()) + 1 if icon_ref else 1
            env.add(Finding(
                "LAUNCH-002", "The app's icons are not finished: %s." % "; ".join(problems),
                file=head_file.rel if head_file else None, line=line if head_file else None, snippet=head_file.line_text(line) if head_file else "",
                confidence="confirmed" if default_icon else "likely", subject={"kind": "project", "name": "icons"},
                detail="Icon and manifest review: %s." % "; ".join(problems),
                fix_hint="Add your own favicon, a touch icon and a web manifest.",
            ))

    # LAUNCH-005: builder branding.
    brand: List[tuple] = []
    for rel in ("vite.config.ts", "vite.config.js", "package.json"):
        sf = project.get(rel)
        if sf and "lovable-tagger" in project.text(sf):
            ln = next((i for i, l in enumerate(sf.lines, 1) if "lovable-tagger" in l), 1)
            brand.append((rel, ln, "the Lovable tagger plugin"))
    if index:
        for needle, label in (("gptengineer.js", "the Lovable editor script"), ("lovable.dev/opengraph", "the Lovable default social image"), ("Made with Bolt", "a \"Made with Bolt\" badge"), ("bolt.new", "a Bolt link"), ("replit-badge", "a Replit badge"), ("Built with v0", "a \"Built with v0\" badge")):
            if needle.lower() in head_text.lower():
                ln = next((i for i, l in enumerate(index.lines, 1) if needle.lower() in l.lower()), 1)
                brand.append((index.rel, ln, label))
    for sf in ui_files:
        if sf.ext == ".html":
            continue
        bm = re.search(r"(?i)(?:made|built|edit(?:ed)?)\s+with\s+(lovable|bolt|v0|replit)", project.text(sf))
        if bm:
            brand.append((sf.rel, sf.line_of(bm.start()), "a \"%s\" badge" % bm.group(0)))
            break
    if brand:
        brand.sort()
        env.add(Finding(
            "LAUNCH-005", "The AI builder's branding and tooling are still in the app: %s." % ", ".join(sorted({b[2] for b in brand})),
            file=brand[0][0], line=brand[0][1], snippet=(project.get(brand[0][0]).line_text(brand[0][1]) if project.get(brand[0][0]) else ""), confidence="confirmed", subject={"kind": "project", "name": "builder-branding"},
            detail="Found in: %s." % ", ".join("%s:%d" % (b[0], b[1]) for b in brand[:6]),
            fix_hint="Remove the badge and scripts where your plan allows it, and replace the default README.",
        ))

    # FE-004: error boundary.
    uses_react = "react" in deps or "vue" in deps or "svelte" in deps
    if uses_react and (is_web or is_mobile) and not has_error_boundary and not detect_stack.has(stack, "error_tracking", "sentry") and fw not in ("expo", "react-native"):
        entry = next((project.get(p) for p in ("src/App.tsx", "src/App.jsx", "src/main.tsx", "src/main.jsx", "app/layout.tsx", "src/app/layout.tsx", "src/App.vue") if project.get(p)), None)
        env.add(Finding(
            "FE-004", "If any part of the page hits an error, the whole app turns into a blank white screen with no way forward.",
            file=entry.rel if entry else None, line=1 if entry else None, snippet=entry.line_text(1) if entry else "", confidence="likely", subject={"kind": "project", "name": "error-boundary"},
            detail="No error boundary, error route file or global error handler was found.",
            fix_hint="Add an error boundary (for Next.js: app/error.tsx and app/global-error.tsx) with a retry action, and report the error to your tracker.",
        ))

    # FE-008: accessibility and mobile basics, one finding.
    a11y = []
    first = None
    html_tag_file = index or layout
    if html_tag_file:
        hm = re.search(r"<html\b([^>]*)>", project.text(html_tag_file))
        if hm and not re.search(r"\blang\s*=", hm.group(1)):
            a11y.append("the page does not declare its language")
            first = (html_tag_file.rel, html_tag_file.line_of(hm.start()))
    if index and not re.search(r"name=[\"']viewport[\"']", head_text):
        a11y.append("no mobile viewport setting")
        first = first or (index.rel, 1)
    if alt_missing:
        a11y.append("%d image(s) without a text description" % len(alt_missing))
        first = first or alt_missing[0]
    if div_click:
        a11y.append("%d clickable element(s) that keyboards and screen readers cannot use" % len(div_click))
        first = first or div_click[0]
    if a11y and first:
        fsf = project.get(first[0])
        env.add(Finding(
            "FE-008", "Some visitors cannot use parts of the app: %s." % "; ".join(a11y),
            file=first[0], line=first[1], snippet=fsf.line_text(first[1]) if fsf else "", confidence="likely", subject={"kind": "project", "name": "accessibility"},
            detail="Automated accessibility basics: %s." % "; ".join(a11y),
            fix_hint="Add lang to <html>, alt text to images, and use buttons or links for clickable elements. Then do a keyboard-only pass.",
        ))

    # PRIV-002: trackers without a consent mechanism.
    if tracker_inv and not consent_present:
        name = sorted(tracker_inv)[0]
        loc = tracker_inv[name][0]
        rel, ln = loc.rsplit(":", 1)
        fsf = project.get(rel)
        env.add(Finding(
            "PRIV-002", "Tracking scripts (%s) load for every visitor before they are asked. In regions that require consent, that is a legal exposure." % ", ".join(sorted(tracker_inv)),
            file=rel, line=int(ln), snippet=fsf.line_text(int(ln)) if fsf else "", confidence="possible", subject={"kind": "project", "name": "trackers"},
            detail="Trackers found with no consent mechanism in the code: %s. Whether consent is required depends on where your users are." % "; ".join("%s (%s)" % (k, v[0]) for k, v in sorted(tracker_inv.items())),
            fix_hint="Load non-essential trackers only after consent, or switch to cookieless analytics.",
        ))

    # PERF-003: large images.
    big = sorted((a for a in project.assets if a.ext in (".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tiff", ".mp4", ".mov", ".webm") and a.size > 1000000), key=lambda a: -a.size)
    for a in big[:5]:
        env.add(Finding(
            "PERF-003", "`%s` is %.1f MB. On a phone connection that one file can take longer to load than the rest of the page." % (a.rel, a.size / 1e6),
            file=a.rel, confidence="confirmed", subject={"kind": "asset", "name": a.rel},
            detail="Asset larger than the 1 MB threshold: %d bytes." % a.size,
            fix_hint="Resize and compress it, serve a modern format (WebP or AVIF), and lazy-load images below the fold.",
        ))

    # PERF-004 (built output): very large entry chunks.
    for bf in project.build_files:
        if bf.ext == ".js" and bf.size > 600000 and re.search(r"(^|/)(assets|chunks|static)/", bf.rel) and not bf.rel.endswith(".map"):
            env.add(Finding(
                "PERF-004", "The built JavaScript file `%s` is %.1f MB, which is slow to download and run on mid-range phones." % (bf.rel, bf.size / 1e6),
                file=bf.rel, confidence="confirmed", subject={"kind": "asset", "name": bf.rel},
                detail="Bundle chunk above the 600 KB threshold.",
                fix_hint="Split by route, load heavy features dynamically, and remove unused libraries.",
            ))
            break

    env.inventory["frontend"] = {"detected": True, "error_boundary": has_error_boundary, "catch_all_route": has_catch_all, "consent_mechanism": consent_present}
    env.inventory["third_party_scripts"] = script_inv
    env.inventory["trackers"] = {k: v for k, v in sorted(tracker_inv.items())}
    env.files_scanned, env.files_skipped = project.stats()
    return env


def main(argv: Optional[List[str]] = None) -> int:
    return findings.run_scanner_cli("scan_frontend", __doc__ or "", scan, argv)


if __name__ == "__main__":
    raise SystemExit(main())
